export const COUNTRY_DISTRICTS_REGISTRY: Record<import('../types').CountryCode, District[]> = {
  IN: DISTRICTS_REGISTRY,
  BR: BRAZIL_DISTRICTS,
  ZA: SOUTH_AFRICA_DISTRICTS,
  RU: RUSSIA_DISTRICTS,
  CN: CHINA_DISTRICTS,
};

export function getDistrictsForCountry(code: import('../types').CountryCode): District[] {
  return COUNTRY_DISTRICTS_REGISTRY[code] || DISTRICTS_REGISTRY;
}

export const ALLOWED_DISTRICT_NAMES = DISTRICTS_REGISTRY.map((d) => d.name).join(', ');

export function getDistrictByName(name: string, countryCode: import('../types').CountryCode = 'IN'): District | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  const list = COUNTRY_DISTRICTS_REGISTRY[countryCode] || DISTRICTS_REGISTRY;
  return list.find(
    (d) => d.name.toLowerCase() === clean || d.id.toLowerCase() === clean
  );
}

